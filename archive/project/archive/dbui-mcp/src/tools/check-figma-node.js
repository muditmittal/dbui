/**
 * dbui_check_figma_node
 *
 * Post-render verifier for the build loop. Given a Figma node ID, returns
 * use_figma JS that walks the node's descendants and reports the ratio of
 * system component instances vs. raw shapes (rectangles, ellipses, polygons,
 * vectors). High instance ratio = the renderer used real DBUI components
 * — pass. Low ratio = drift / "static drawing" — fail.
 *
 * This catches the exact failure mode demonstrated in the screenshot eval:
 * the agent drew rectangles instead of using component instances.
 *
 * Usage:
 *   1. Render via dbui_render_figma → use_figma → get back outerFrameId.
 *   2. Pass outerFrameId to this tool.
 *   3. The returned `code` is JS for use_figma. Run it to get the breakdown.
 *   4. Result includes pass/fail + a list of suspicious raw-shape paths
 *      so the agent can fix specific drift sites.
 */
import { fileURLToPath } from "node:url"

const __filename = fileURLToPath(import.meta.url)

function escapeJsString(s) {
  return JSON.stringify(s)
}

export const tool = {
  name: "dbui_check_figma_node",
  description:
    "Post-render check. Given a Figma node ID (e.g. the outerFrameId returned by dbui_render_figma → use_figma), returns use_figma JS that walks descendants and reports the ratio of system component INSTANCEs to raw shapes (rectangles, ellipses, polygons, vectors). Pass if instances >= threshold (default 0.6). Identifies specific raw-shape nodes so you know what to convert. Use this AFTER rendering to confirm the output isn't a static drawing.",
  inputSchema: {
    type: "object",
    properties: {
      nodeId: {
        type: "string",
        description: "The Figma node ID to verify. Typically the outerFrameId returned by use_figma after running dbui_render_figma's code.",
      },
      threshold: {
        type: "number",
        description:
          "Minimum instance-to-shape ratio for the check to pass. 0–1. Default 0.6 (60% of shape-like nodes must be component instances).",
        default: 0.6,
      },
      maxRawSamples: {
        type: "number",
        description: "Max number of raw-shape sample paths to return for inspection. Default 20.",
        default: 20,
      },
    },
    required: ["nodeId"],
  },
}

export function run({ nodeId, threshold = 0.6, maxRawSamples = 20 }) {
  if (!nodeId) {
    return { code: null, error: "nodeId is required" }
  }

  const code = `
// Generated by dbui_check_figma_node — DO NOT hand-edit.
const root = await figma.getNodeByIdAsync(${escapeJsString(nodeId)});
if (!root) return { ok: false, error: "Node not found: ${nodeId}" };

// Walk descendants. Categorize each node by type.
//   INSTANCE       → system component (good)
//   RECTANGLE/ELLIPSE/POLYGON/VECTOR/STAR/LINE → raw shape (drift candidate)
//   TEXT/GROUP/SECTION                          → neutral (fine inside instances)
//   FRAME                                       → neutral but flagged if it has visible fills
//                                                 OR if it's a top-level free-floating frame
const counts = { instance: 0, rawShape: 0, text: 0, frame: 0, neutral: 0 };
const rawSamples = [];
const RAW_TYPES = new Set(["RECTANGLE", "ELLIPSE", "POLYGON", "VECTOR", "STAR", "LINE"]);

function pathOf(node) {
  const parts = [];
  let cur = node;
  while (cur && cur.id !== root.id) {
    parts.unshift(cur.name || cur.type);
    cur = cur.parent;
  }
  parts.unshift(root.name || root.type);
  return parts.join(" > ");
}

function walk(node) {
  if (!node) return;
  // The root itself doesn't count.
  if (node.id !== root.id) {
    if (node.type === "INSTANCE") {
      counts.instance++;
      // Don't descend into instances — their internals are part of the system component.
      return;
    }
    if (RAW_TYPES.has(node.type)) {
      counts.rawShape++;
      if (rawSamples.length < ${maxRawSamples}) {
        rawSamples.push({
          id: node.id,
          type: node.type,
          name: node.name || "",
          path: pathOf(node),
          width: Math.round(node.width || 0),
          height: Math.round(node.height || 0),
        });
      }
    } else if (node.type === "TEXT") {
      counts.text++;
    } else if (node.type === "FRAME" || node.type === "GROUP" || node.type === "SECTION") {
      counts.frame++;
    } else {
      counts.neutral++;
    }
  }
  if ("children" in node && Array.isArray(node.children)) {
    for (const child of node.children) walk(child);
  }
}

walk(root);

const denom = counts.instance + counts.rawShape;
const ratio = denom > 0 ? counts.instance / denom : 1;
const passed = ratio >= ${threshold};

return {
  ok: true,
  nodeId: root.id,
  nodeName: root.name,
  threshold: ${threshold},
  ratio: Math.round(ratio * 1000) / 1000,
  passed,
  counts,
  rawSamples,
  summary: passed
    ? "PASS — output uses system component instances (ratio " + Math.round(ratio * 100) + "%, threshold " + Math.round(${threshold} * 100) + "%).":
      "FAIL — too many raw shapes (ratio " + Math.round(ratio * 100) + "%, threshold " + Math.round(${threshold} * 100) + "%). Convert the raw shapes listed in rawSamples to DBUI component instances. This is the same failure mode as the screenshot eval — drawing instead of using the system."
};
`.trim()

  return {
    code,
    usage:
      "Pass `code` to use_figma's `code` parameter. The result includes ratio (0–1), pass/fail, counts per node type, and a sample of raw-shape paths to fix.",
  }
}
