#!/usr/bin/env node
/**
 * Emits the utility surface for the portal's Utilities page.
 *
 * Three things are read, none of them restated on the page:
 *   - every export of `packages/dbui/src/lib/`, with its signature and whether
 *     the barrel re-exports it
 *   - every `@utility` the token layer emits, split into the type ramp and the
 *     rest, because the ramp is documented on the Tokens page and the rest is
 *     documented nowhere else
 *   - the import path each module answers to, from the package's export map
 *
 * A helper added to `lib/` therefore appears on the page without anyone editing
 * it, which is the only way a page about a directory stays true to it.
 *
 *   node scripts/generate-utility-data.mjs
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const LIB = path.join(ROOT, "packages/dbui/src/lib")
const TOKENS = path.join(ROOT, "packages/dbui/src/tokens")
const BARREL = path.join(ROOT, "packages/dbui/src/index.ts")
const OUT = path.join(ROOT, "apps/portal/src/components/utility-data.ts")

const read = (file) => fs.readFileSync(file, "utf8")

/**
 * The declaration head, without the body. Angle brackets are tracked separately
 * from parens because a type parameter can hold an arrow type, and its `=>`
 * would otherwise end the scan a generic early.
 */
function headOf(source, from, kind) {
  let angle = 0
  let paren = 0
  for (let i = from; i < source.length; i++) {
    const ch = source[i]
    if (ch === "<") angle++
    else if (ch === ">") angle = Math.max(0, angle - 1)
    else if (ch === "(") paren++
    else if (ch === ")") paren--
    else if (angle === 0 && paren === 0) {
      // A function head ends at its body, everything else at its initialiser.
      if (kind === "function" ? ch === "{" : ch === "=") {
        return source.slice(from, i).replace(/\s+/g, " ").trim()
      }
    }
  }
  return source.slice(from).replace(/\s+/g, " ").trim()
}

/** `export function|const|type|interface NAME` — the whole surface of these files. */
function exportsOf(source) {
  const found = []
  const re = /export\s+(function|const|type|interface)\s+([A-Za-z_$][\w$]*)/g
  let match
  while ((match = re.exec(source))) {
    const [, kind, name] = match
    found.push({ name, kind, signature: headOf(source, match.index + match[0].length - name.length, kind) })
  }
  return found
}

const barrel = read(BARREL)

const modules = fs
  .readdirSync(LIB)
  .filter((f) => f.endsWith(".ts"))
  .sort()
  .map((file) => {
    const name = file.replace(/\.ts$/, "")
    return {
      module: `lib/${name}`,
      importPath: `dbui/lib/${name}`,
      // The barrel re-exports a module or it does not. Consumers import by
      // path either way, so this records reach rather than availability.
      inBarrel: barrel.includes(`"./lib/${name}"`),
      exports: exportsOf(read(path.join(LIB, file))),
    }
  })

/** `@utility NAME { … }` across every stylesheet the token layer ships. */
function cssUtilities() {
  const found = []
  for (const file of fs.readdirSync(TOKENS).filter((f) => f.endsWith(".css"))) {
    const source = read(path.join(TOKENS, file))
    for (const [, name, body] of source.matchAll(/@utility\s+([a-z0-9-]+)\s*\{([\s\S]*?)\n\}/g)) {
      found.push({
        name,
        source: `tokens/${file}`,
        declarations: body
          .split("\n")
          .map((line) => line.trim())
          .filter(Boolean),
      })
    }
  }
  return found
}

const css = cssUtilities()
const ramp = css.filter((u) => u.name.startsWith("type-")).map((u) => u.name)
const standalone = css.filter((u) => !u.name.startsWith("type-"))

const banner = `// Generated by scripts/generate-utility-data.mjs — do not edit by hand.
// Sources: packages/dbui/src/lib/, packages/dbui/src/tokens/*.css, packages/dbui/src/index.ts
`

const types = `
export type UtilityExport = { name: string; kind: string; signature: string }

export type UtilityModule = {
  module: string
  importPath: string
  inBarrel: boolean
  exports: UtilityExport[]
}

export type CssUtility = { name: string; source: string; declarations: string[] }
`

fs.writeFileSync(
  OUT,
  [
    banner,
    types,
    `\nexport const utilityModules: UtilityModule[] = ${JSON.stringify(modules, null, 2)}\n`,
    `\n/** Documented on the Tokens page, where the ramp they come from is rendered. */`,
    `\nexport const rampUtilities: string[] = ${JSON.stringify(ramp, null, 2)}\n`,
    `\nexport const cssUtilities: CssUtility[] = ${JSON.stringify(standalone, null, 2)}\n`,
  ].join("")
)

const exported = modules.reduce((n, m) => n + m.exports.length, 0)
console.log(
  `utility-data.ts — ${exported} exports across ${modules.length} modules, ` +
    `${standalone.length} CSS utilities, ${ramp.length} ramp utilities`
)
