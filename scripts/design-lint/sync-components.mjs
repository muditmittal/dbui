#!/usr/bin/env node
/**
 * sync-components — regenerates scripts/design-lint/dbui-components.json from
 * the packages themselves.
 *
 * The file used to be hand-maintained, and its own `$source` pointed at a
 * `sync-components.ts` that has never existed. It had drifted both ways: 49
 * real exports missing, including DataTree and FileTree, and 11 names still
 * listed that nothing exports any more, including Tree, Shell and IconButton.
 * The icons key held the string "$see icons.json" rather than any icons, so
 * every DBUI icon in the tree came back as an unknown component — 803 findings,
 * three fifths of everything the rule reported.
 *
 * The public surface is each package's barrel, resolved through `export *` by
 * the compiler rather than by a regex, so a re-export cannot go missing. Icons
 * are read from their directory: one component per file, named after the file.
 *
 * Only the name lists live here. Which plain HTML tags are allowed is a rule
 * rather than a fact about the packages, so it belongs to the linter.
 *
 * Usage:  node scripts/design-lint/sync-components.mjs
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
// ts-morph is CommonJS, so its enums do not survive a named ESM import, and
// JsxEmit lives on the re-exported compiler rather than at the top level.
import tsMorph from "ts-morph"
const { ModuleResolutionKind, Project, SyntaxKind, ts } = tsMorph

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, "../../")
const OUT = path.join(__dirname, "dbui-components.json")

const PACKAGES = [
  { key: "ui", barrel: "packages/dbui/src/index.ts" },
  { key: "shells", barrel: "packages/dbui-shells/src/index.ts" },
  { key: "chat", barrel: "packages/dbui-chat/src/index.ts" },
  { key: "viz", barrel: "packages/dbui-viz/src/index.ts" },
]
const ICON_DIR = "packages/dbui/src/components/icons"

/* A JSX tag is a value and starts with a capital. A type alias cannot be
 * rendered, so `PromptInputProps` and `ChatStatus` stay out.
 *
 * Stated as what to exclude rather than what to allow. An allowlist of value
 * kinds silently drops a re-export the compiler could not follow across a
 * workspace boundary — which is how `ButtonIcon as SuggestionIcon` went
 * missing, and the linter then reported the one file importing it as a broken
 * import. Excluding types keeps an unresolved name, which is the safer way to
 * be wrong: a name that should not be here is inert, and a name that is
 * missing accuses working code. */
const TYPE_KINDS = new Set([
  SyntaxKind.TypeAliasDeclaration,
  SyntaxKind.InterfaceDeclaration,
  SyntaxKind.TypeParameter,
])
// Capitalised and unbroken. The underscore is what separates a constant like
// DATA_KIND_ICON from a component, not the case — DAG, ERD, MCP and H1 through
// H6 are all-caps icons that something renders.
const isComponentName = (n) => /^[A-Z][A-Za-z0-9]*$/.test(n)

// Both options are load-bearing. Without `jsx` the compiler refuses every .tsx
// behind a barrel and the export map comes back empty, which reads exactly like
// a package with no components.
const project = new Project({
  skipAddingFilesFromTsConfig: true,
  compilerOptions: { jsx: ts.JsxEmit.ReactJSX, moduleResolution: ModuleResolutionKind.Bundler },
})

const out = {
  $comment:
    "Every DBUI export, by package. Anything used in design or code that is not in one of these lists is reported as a non-DBUI component.",
  $source: "GENERATED by scripts/design-lint/sync-components.mjs. Do not hand-edit — re-run it instead.",
}

for (const { key, barrel } of PACKAGES) {
  const abs = path.join(ROOT, barrel)
  if (!fs.existsSync(abs)) throw new Error(`Missing barrel: ${barrel}`)
  const sf = project.addSourceFileAtPath(abs)
  project.resolveSourceFileDependencies()
  const names = new Set()
  for (const [name, decls] of sf.getExportedDeclarations()) {
    if (!isComponentName(name)) continue
    if (decls.length && decls.every((d) => TYPE_KINDS.has(d.getKind()))) continue
    names.add(name)
  }
  out[key] = [...names].sort()
}

const iconDir = path.join(ROOT, ICON_DIR)
out.icons = fs
  .readdirSync(iconDir)
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => f.replace(/\.tsx$/, ""))
  .filter(isComponentName)
  .sort()

fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n")

const counts = PACKAGES.map(({ key }) => `${out[key].length} ${key}`).join(", ")
console.log(`dbui-components.json : ${counts}, ${out.icons.length} icons.`)
