#!/usr/bin/env node
/**
 * Emits the page shells for the portal's Shells page.
 *
 * Read through the CLI API, which parses composition.md — the same source
 * agents get from `dbui shell`, so the page cannot describe a shell the system
 * does not have.
 *
 *   node scripts/generate-shell-data.mjs
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { shellList, shell } from "../packages/dbui-cli/src/api.mjs"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const OUT = path.join(ROOT, "apps/portal/src/components/shell-data.ts")

/** Region lines carry inline markdown; the page renders plain text. */
const clean = (s) => String(s ?? "").replace(/`/g, "").trim()

const list = shellList().data.shells ?? shellList().data
const shells = (Array.isArray(list) ? list : []).map((s) => {
  const full = shell(s.id).data
  return {
    id: full.id,
    name: full.name,
    purpose: clean(full.purpose),
    regions: (full.regions ?? []).map(clean),
    scaling: clean(full.scaling),
    scroll: clean(full.scroll),
  }
})

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-shell-data.mjs — do not edit by hand.
// Source: packages/dbui/composition.md, via the CLI API.

export type Shell = {
  id: string
  name: string
  purpose: string
  regions: string[]
  scaling: string
  scroll: string
}

export const shells: Shell[] = ${JSON.stringify(shells, null, 2)}
`
)

console.log(`wrote ${path.relative(ROOT, OUT)}`)
for (const s of shells) console.log(`  ${s.id}  ${s.name} — ${s.regions.length} regions`)
